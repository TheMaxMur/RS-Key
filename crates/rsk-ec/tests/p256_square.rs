use p256::elliptic_curve::{PrimeField, bigint::Word, hazmat::FieldArithmetic};

type Element = <p256::NistP256 as FieldArithmetic>::FieldElement;
const ONE_SQUARED: Element = Element::ONE.square();

fn element(bytes: [u8; 32]) -> Element {
    Option::<Element>::from(Element::from_repr(bytes.into())).unwrap()
}

#[test]
fn requested_word_width_is_exercised() {
    if let Some(bits) = option_env!("RSK_TEST_WORD_BITS") {
        assert_eq!(Word::BITS, bits.parse::<u32>().unwrap());
    }
}

#[test]
fn square_remains_const_evaluable() {
    assert_eq!(ONE_SQUARED, Element::ONE);
}

#[test]
fn square_matches_independent_canonical_vectors() {
    for (input, expected) in VECTORS {
        assert_eq!(element(input).square().to_repr().as_slice(), expected);
    }
}

#[test]
fn square_matches_multiply_at_boundaries_and_dense_values() {
    for (input, _) in VECTORS {
        let value = element(input);
        assert_eq!(value.square(), value * value);
    }
    let mut state = 0x906e_31fa_d482_7b15_u64;
    let mut accepted = 0;
    for _ in 0..2048 {
        let mut bytes = [0; 32];
        for chunk in bytes.as_chunks_mut::<8>().0.iter_mut() {
            state ^= state << 13;
            state ^= state >> 7;
            state ^= state << 17;
            chunk.copy_from_slice(&state.to_be_bytes());
        }
        if let Some(value) = Option::<Element>::from(Element::from_repr(bytes.into())) {
            assert_eq!(value.square(), value * value);
            accepted += 1;
        }
    }
    assert!(accepted >= 2040);
}

