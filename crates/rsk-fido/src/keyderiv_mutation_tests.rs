#[test]
fn the_ratchet_and_ctap_path_match_independent_hkdf_transcripts() {
    let mut path = [0; 32];
    for (index, byte) in path.iter_mut().enumerate() {
        *byte = index as u8;
    }
    assert_eq!(ratchet(&SEED, &path).expose(), &RATCHET);
    assert_eq!(fido_load_key(&SEED, &path).unwrap().expose(), &CTAP);
}

#[test]
fn authenticated_handles_still_require_each_paths_hardened_bit() {
    assert_eq!(
        verify_key(&SEED, &APP, &HARD_HANDLE).unwrap().expose(),
        &HARD_SCALAR
    );
    assert!(verify_key(&SEED, &APP, &SOFT_HANDLE).is_none());
}

#[test]
fn new_handles_preserve_already_hardened_entries_and_match_the_known_key() {
    struct PathRng(u8);
    impl Rng for PathRng {
        fn fill(&mut self, output: &mut [u8]) {
            assert_eq!(output.len(), 4);
            output.copy_from_slice(&[self.0, self.0 + 1, self.0 + 2, 0x80]);
            self.0 += 4;
        }
    }
    let mut rng = PathRng(0);
    let (handle, scalar) = derive_new(&SEED, &APP, &mut rng);
    assert_eq!(handle, HARD_HANDLE);
    assert_eq!(scalar.expose(), &HARD_SCALAR);
    assert_eq!(rng.0, 32);
}
